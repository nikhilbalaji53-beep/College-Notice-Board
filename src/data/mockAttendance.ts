export function getAttendanceStats(students: StudentAttendance[] = MOCK_STUDENTS_ATTENDANCE) {
  const total = students.length;
  const critical = students.filter(s => s.percentage < 65).length;
  const warning = students.filter(s => s.percentage >= 65 && s.percentage < 75).length;
  const eligible = students.filter(s => s.percentage >= 75).length;
  const excellent = students.filter(s => s.percentage >= 85).length;
  const totalPercentage = students.reduce((sum, s) => sum + s.percentage, 0);
  const averagePercentage = total > 0 ? (totalPercentage / total).toFixed(1) : '0';

  return {
    total,
    critical,
    warning,
    totalShortage: critical + warning,
    eligible,
    excellent,
    averagePercentage: parseFloat(averagePercentage)
  };
}
